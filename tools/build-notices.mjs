// Regenerates THIRD-PARTY-NOTICES.md (and the plain-text copy served with the site in
// public/) from the licence files of the packages that ship in the build.
// Run: npm run notices
import { readFileSync, writeFileSync } from 'node:fs';

const pkg = (name) => JSON.parse(readFileSync(`node_modules/${name}/package.json`, 'utf8'));
const text = (path) => readFileSync(path, 'utf8').trim();

const shipped = [
  { name: 'react', use: 'User interface' },
  { name: 'react-dom', use: 'User interface' },
  { name: 'scheduler', use: 'Dependency of react-dom' },
  { name: 'three', use: '3D rendering, including the bundled GLTFLoader, OrbitControls and meshopt decoder add-ons' },
  { name: 'sql.js', use: 'SQLite compiled to WebAssembly, for the SQL quest' },
];

let out = `# Third-party notices

CurioTrail includes the third-party material listed here. **Each item keeps its own licence.** CurioTrail's own licence does not apply to it, and nothing in CurioTrail's terms restricts what that licence allows. The SG · CurioTrail mark and copyright notice refer to CurioTrail's own work only.

This file is generated by \`tools/build-notices.mjs\` from the licence files of the installed packages. A plain-text copy is served with the game at \`THIRD-PARTY-NOTICES.txt\`, because browsers display plain text but may download Markdown.

## Summary

| Material | Version | Licence | Copyright | Used for |
|---|---|---|---|---|
`;
for (const s of shipped) {
  const p = pkg(s.name);
  const copyright = text(`node_modules/${s.name}/LICENSE`).split('\n').find((l) => /copyright/i.test(l)).trim();
  out += `| ${s.name} | ${p.version} | ${p.license} | ${copyright} | ${s.use} |\n`;
}
out += `| meshoptimizer decoder (inside three) | as bundled with three | MIT | Copyright (C) 2016-2026, by Arseny Kapoulkine | Decompressing the island models |
| SQLite (inside sql.js) | as bundled with sql.js | Public domain | none claimed | The database engine |
| "Viking Island - Minecraft" 3D model (derivative) | n/a | CC-BY-4.0 | cubical.xyz | The island (\`models/island-high.glb\`, \`models/island-low.glb\`) |

Build tools (Vite, TypeScript, Vitest, glTF-Transform, meshoptimizer's encoder and pngjs) are used to build and test CurioTrail but are not shipped in the game. No third-party fonts, images, sounds or textures are shipped: the game uses system fonts and emoji, and the island's original Minecraft-style texture atlas is not included.

## 3D island model (CC-BY-4.0)

\`models/island-high.glb\` and \`models/island-low.glb\` are based on ["Viking Island - Minecraft"](https://sketchfab.com/3d-models/viking-island-minecraft-fd76e3824b7647d98be20d3e2160e018) by [cubical.xyz](https://sketchfab.com/cubical), licensed under [CC-BY-4.0](http://creativecommons.org/licenses/by/4.0/).

Changes: merged into chunks, baked to flat per-face colours (the original texture atlas is not included), water and seabed removed, simplified, quantized and meshopt-compressed. See \`tools/optimize-island.mjs\`.

These two files remain under CC-BY-4.0. Anyone may reuse them under that licence, with attribution, whatever CurioTrail's own terms say. The original creator does not endorse CurioTrail.

## SQLite

SQLite, compiled into sql.js, is in the public domain. See https://www.sqlite.org/copyright.html.

## Licence texts
`;
for (const s of shipped) {
  out += `\n### ${s.name} ${pkg(s.name).version}\n\n\`\`\`text\n${text(`node_modules/${s.name}/LICENSE`)}\n\`\`\`\n`;
}
const meshopt = readFileSync('node_modules/three/examples/jsm/libs/meshopt_decoder.module.js', 'utf8').split('\n').slice(0, 2).join('\n');
out += `\n### meshoptimizer decoder\n\nThe file header reads:\n\n\`\`\`text\n${meshopt}\n\`\`\`\n\nThe MIT License text is the same as for three above, with this copyright line.\n`;

writeFileSync('THIRD-PARTY-NOTICES.md', out);
writeFileSync('public/THIRD-PARTY-NOTICES.txt', out);
console.log('Wrote THIRD-PARTY-NOTICES.md and public/THIRD-PARTY-NOTICES.txt');
